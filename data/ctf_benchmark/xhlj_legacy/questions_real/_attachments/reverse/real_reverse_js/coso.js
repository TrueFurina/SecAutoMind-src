function enlog(str) {
    var arr = str.split('');
    for (var i = 0; i < arr.length; i++) {
        if (arr[i].match(/[A-Za-z]/)) {
            var code = arr[i].charCodeAt() + 13;
            if (code > 90 && code < 104 || code > 122) {
                code -= 26;
            }
            arr[i] = String.fromCharCode(code);
        }
    }
    return arr.join('');
}

function delog(str) {
    var arr = str.split('');
    for (var i = 0; i < arr.length; i++) {
        if (arr[i].match(/[A-Za-z]/)) {
            var code = arr[i].charCodeAt() - 13;
            if (code < 65 || code > 90 && code < 97) {
                code += 26;
            }
            arr[i] = String.fromCharCode(code);
        }
    }
    return arr.join('');
}


